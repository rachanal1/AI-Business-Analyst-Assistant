-- Purpose:
-- Calculate the main business KPIs used to analyze
-- orders, revenue, customers, products, sellers,
-- payments, delivery, and reviews.
-- ============================================================


-- KPI 1:
-- Calculate the total number of unique orders.
SELECT COUNT(DISTINCT order_id) AS total_orders
FROM orders;


-- KPI 2:
-- Calculate the total revenue generated from order items.
SELECT ROUND(SUM(price), 2) AS total_revenue
FROM order_items;


-- KPI 3:
-- Calculate the total number of unique customers.
SELECT COUNT(DISTINCT customer_unique_id) AS total_customers
FROM customers;


-- KPI 4:
-- Calculate revenue generated by each product category.
SELECT
    p.product_category_name,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY p.product_category_name
ORDER BY total_revenue DESC;


-- KPI 5:
-- Find the product category that generated the highest revenue.
SELECT
    p.product_category_name,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY p.product_category_name
ORDER BY total_revenue DESC
LIMIT 1;


-- KPI 6:
-- Calculate total revenue for each month.
SELECT
    DATE_TRUNC('month', o.order_purchase_timestamp) AS month,
    ROUND(SUM(oi.price), 2) AS monthly_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY DATE_TRUNC('month', o.order_purchase_timestamp)
ORDER BY month;


-- KPI 7:
-- Calculate monthly order count and monthly revenue.
SELECT
    DATE_TRUNC('month', o.order_purchase_timestamp) AS month,
    COUNT(DISTINCT o.order_id) AS total_orders,
    ROUND(SUM(oi.price), 2) AS revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY DATE_TRUNC('month', o.order_purchase_timestamp)
ORDER BY month;


-- KPI 8:
-- Calculate the number of orders placed by each customer.
SELECT
    c.customer_unique_id,
    COUNT(DISTINCT o.order_id) AS total_orders
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_unique_id
ORDER BY total_orders DESC;


-- KPI 9:
-- Find the top 10 customers based on total spending.
SELECT
    c.customer_unique_id,
    ROUND(SUM(oi.price), 2) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY c.customer_unique_id
ORDER BY total_spending DESC
LIMIT 10;


-- KPI 10:
-- Calculate the average spending per customer.
SELECT
    ROUND(AVG(total_spending), 2) AS average_customer_spending
FROM (
    SELECT
        c.customer_unique_id,
        SUM(oi.price) AS total_spending
    FROM customers c
    JOIN orders o
        ON c.customer_id = o.customer_id
    JOIN order_items oi
        ON o.order_id = oi.order_id
    GROUP BY c.customer_unique_id
) customer_spending;


-- KPI 11:
-- Find the top 10 products based on total revenue.
SELECT
    oi.product_id,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM order_items oi
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY oi.product_id
ORDER BY total_revenue DESC
LIMIT 10;


-- KPI 12:
-- Find the top 10 products based on units sold.
SELECT
    product_id,
    COUNT(*) AS units_sold
FROM order_items
GROUP BY product_id
ORDER BY units_sold DESC
LIMIT 10;


-- KPI 13:
-- Compare the number of products and revenue
-- for each product category.
SELECT
    p.product_category_name,
    COUNT(DISTINCT p.product_id) AS product_count,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_category_name
ORDER BY total_revenue DESC;


-- KPI 14:
-- Find the top 5 product categories by revenue.
SELECT
    p.product_category_name,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_category_name
ORDER BY total_revenue DESC
LIMIT 5;


-- KPI 15:
-- Find the top 10 sellers based on revenue.
SELECT
    s.seller_id,
    ROUND(SUM(oi.price), 2) AS total_revenue
FROM sellers s
JOIN order_items oi
    ON s.seller_id = oi.seller_id
GROUP BY s.seller_id
ORDER BY total_revenue DESC
LIMIT 10;


-- KPI 16:
-- Find the top 10 sellers based on number of orders.
SELECT
    s.seller_id,
    COUNT(DISTINCT oi.order_id) AS total_orders
FROM sellers s
JOIN order_items oi
    ON s.seller_id = oi.seller_id
GROUP BY s.seller_id
ORDER BY total_orders DESC
LIMIT 10;


-- KPI 17:
-- Find the top 10 sellers based on units sold.
SELECT
    s.seller_id,
    COUNT(*) AS units_sold
FROM sellers s
JOIN order_items oi
    ON s.seller_id = oi.seller_id
GROUP BY s.seller_id
ORDER BY units_sold DESC
LIMIT 10;


-- KPI 18:
-- Count how frequently each payment type is used.
SELECT
    payment_type,
    COUNT(*) AS payment_count
FROM order_payments
GROUP BY payment_type
ORDER BY payment_count DESC;


-- KPI 19:
-- Calculate total payment value by payment type.
SELECT
    payment_type,
    ROUND(SUM(payment_value), 2) AS total_payment_value
FROM order_payments
GROUP BY payment_type
ORDER BY total_payment_value DESC;


-- KPI 20:
-- Calculate average payment installments
-- for each payment type.
SELECT
    payment_type,
    ROUND(AVG(payment_installments), 2) AS avg_installments
FROM order_payments
GROUP BY payment_type
ORDER BY avg_installments DESC;


-- KPI 21:
-- Count the number of orders for each order status.
SELECT
    order_status,
    COUNT(*) AS order_count
FROM orders
GROUP BY order_status
ORDER BY order_count DESC;


-- KPI 22:
-- Calculate the average delivery time in days
-- from purchase to customer delivery.
SELECT
    ROUND(
        AVG(
            EXTRACT(
                EPOCH FROM (
                    order_delivered_customer_date
                    - order_purchase_timestamp
                )
            ) / 86400
        ),
        2
    ) AS average_delivery_days
FROM orders
WHERE order_delivered_customer_date IS NOT NULL;


-- KPI 23:
-- Classify delivered orders as Late or On Time.
SELECT
    CASE
        WHEN order_delivered_customer_date
             > order_estimated_delivery_date
        THEN 'Late'
        ELSE 'On Time'
    END AS delivery_status,
    COUNT(*) AS order_count
FROM orders
WHERE order_delivered_customer_date IS NOT NULL
GROUP BY
    CASE
        WHEN order_delivered_customer_date
             > order_estimated_delivery_date
        THEN 'Late'
        ELSE 'On Time'
    END;


-- KPI 24:
-- Calculate the average customer review score.
SELECT
    ROUND(AVG(review_score), 2) AS average_review_score
FROM order_reviews;


-- KPI 25:
-- Count how many reviews exist for each review score.
SELECT
    review_score,
    COUNT(*) AS review_count
FROM order_reviews
GROUP BY review_score
ORDER BY review_score;


-- KPI 26:
-- Find orders that received a poor review score
-- of 1 or 2.
SELECT
    order_id,
    review_score
FROM order_reviews
WHERE review_score <= 2
ORDER BY review_score;


-- KPI 27:
-- Calculate the percentage of reviews
-- with a score of 1 or 2.
SELECT
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE review_score <= 2)
        / COUNT(*),
        2
    ) AS poor_review_percentage
FROM order_reviews;